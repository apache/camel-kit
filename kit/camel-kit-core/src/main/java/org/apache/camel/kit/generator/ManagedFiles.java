package org.apache.camel.kit.generator;

import java.io.IOException;
import java.io.StringWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Collection;
import java.util.HashSet;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Decides how initialization treats a file that an existing project can already own.
 *
 * <p>
 * Camel-Kit writes a small set of files at paths that are not specific to Camel-Kit, such as {@code AGENTS.md} or
 * {@code mvnw}. They are handled in one of two ways:
 * <ul>
 * <li>Markdown instruction files carry Camel-Kit's content inside a marked block. Initialization replaces only that
 * block, or appends it to a file that has none, so everything the user wrote around it survives.</li>
 * <li>Every other shared file is tracked in a ledger holding the hash of the content Camel-Kit last wrote. The file is
 * replaced only when it is missing or still matches that hash. Otherwise it belongs to the user: it is left untouched,
 * reported as a conflict, and the content Camel-Kit would have written is saved under {@code .camel-kit/conflicts/} for
 * manual merging.</li>
 * </ul>
 * A shared file named explicitly for replacement is always rewritten in full.
 *
 * <p>
 * Files under Camel-Kit's own names (skills, personas, subagents, {@code .camel-kit/}) are not protected and are always
 * regenerated.
 */
public final class ManagedFiles {

    /** Project-relative ledger of the shared files Camel-Kit wrote and the hash of what it wrote. */
    public static final String LEDGER = ".camel-kit/managed-files.properties";

    /** Project-relative directory holding the content Camel-Kit would have written to a preserved file. */
    public static final String PROPOSALS = ".camel-kit/conflicts";

    public static final String BLOCK_START = "<!-- CAMEL-KIT-MANAGED-BLOCK-START: camel-kit-generated -->";
    public static final String BLOCK_END = "<!-- CAMEL-KIT-MANAGED-BLOCK-END: camel-kit-generated -->";

    private static final String BLOCK_NOTE
            = "<!-- Generated by camel-kit init. This block is replaced on reinitialization; "
              + "keep your own content outside it. -->";
    private static final Pattern BLOCK = Pattern.compile(
            Pattern.quote(BLOCK_START) + ".*?" + Pattern.quote(BLOCK_END) + "(\\r?\\n)?", Pattern.DOTALL);

    /** Instruction files that hold Camel-Kit's content in a marked block next to the user's own. */
    private static final Set<String> MERGED = Set.of(
            "AGENTS.md",
            "CLAUDE.md",
            "QWEN.md",
            ".github/copilot-instructions.md");

    /** Files replaced as a whole, and only while they still hold what Camel-Kit wrote. */
    private static final Set<String> TRACKED = Set.of(
            ".qwenignore",
            ".claude/settings.json",
            ".bob/custom_modes.yaml",
            "docs/constitution.md",
            "mvnw",
            "mvnw.cmd",
            ".mvn/wrapper/maven-wrapper.properties");

    /** What initialization does, or would do, to a shared file. */
    public enum Action {
        /** The file does not exist and is written. */
        CREATE,
        /** The file holds what Camel-Kit wrote, or was named for replacement, and is rewritten. */
        REFRESH,
        /** Camel-Kit's block is added to, or replaced inside, a file that also holds the user's content. */
        MERGE,
        /** The file belongs to the user and is left untouched. */
        PRESERVE
    }

    /**
     * The outcome for one shared file.
     *
     * @param path     project-relative path, using {@code /} separators
     * @param proposal for a preserved file, where the content Camel-Kit would have written was saved, when it was
     */
    public record Change(String path, Action action, Path proposal) {
    }

    private final Path projectDir;
    /** Only for callers outside initialization, which never protect existing files. */
    private final boolean unrestricted;
    private final Set<String> replace;
    private final Set<String> usedReplacements = new HashSet<>();
    private final Properties ledger;
    private final Map<String, Change> changes = new LinkedHashMap<>();

    private ManagedFiles(Path projectDir, boolean unrestricted, Set<String> replace, Properties ledger) {
        this.projectDir = projectDir;
        this.unrestricted = unrestricted;
        this.replace = replace;
        this.ledger = ledger;
    }

    /** Rewrites every file in full, as initialization did before shared files were protected. */
    public static ManagedFiles unrestricted(Path projectDir) {
        return new ManagedFiles(projectDir.toAbsolutePath().normalize(), true, Set.of(), new Properties());
    }

    /**
     * Opens the ledger of a project without writing anything.
     *
     * <p>
     * A missing ledger, or a file missing from it, never implies ownership: a workspace initialized before the ledger
     * existed is treated like any other existing project, so its unmarked instruction files are merged and its other
     * shared files are preserved until they are named for replacement.
     *
     * @param  replace                  project-relative shared files the user explicitly asked to replace
     * @throws IllegalArgumentException when a replacement is not a shared file Camel-Kit writes
     */
    public static ManagedFiles open(Path projectDir, Collection<String> replace) throws IOException {
        Path root = projectDir.toAbsolutePath().normalize();
        Set<String> replacements = new HashSet<>();
        for (String requested : replace) {
            Path resolved = root.resolve(requested).normalize();
            String key = resolved.startsWith(root) ? key(root, resolved) : requested;
            if (!isShared(key)) {
                Set<String> shared = new TreeSet<>(MERGED);
                shared.addAll(TRACKED);
                throw new IllegalArgumentException(
                        "Cannot replace '" + requested + "': not a shared file written by init. Replaceable files: "
                                                   + String.join(", ", shared));
            }
            replacements.add(key);
        }
        Properties ledger = new Properties();
        Path ledgerFile = root.resolve(LEDGER);
        if (Files.isRegularFile(ledgerFile, LinkOption.NOFOLLOW_LINKS)) {
            try (var in = Files.newBufferedReader(ledgerFile)) {
                ledger.load(in);
            }
        }
        return new ManagedFiles(root, false, replacements, ledger);
    }

    /** What {@link #write} would do to this file. Reads only: nothing is written or recorded. */
    public Action plan(Path target) throws IOException {
        String key = key(target);
        if (!Files.exists(target, LinkOption.NOFOLLOW_LINKS)) {
            return Action.CREATE;
        }
        if (!isShared(key) || unrestricted || replace.contains(key)) {
            return Action.REFRESH;
        }
        if (!Files.isRegularFile(target, LinkOption.NOFOLLOW_LINKS)) {
            return Action.PRESERVE;
        }
        if (MERGED.contains(key)) {
            // Without a block the content is the user's, whoever wrote it first: the block is appended. Markers
            // that do not form exactly one ordered pair cannot be located safely and are never guessed at.
            String existing = Files.readString(target);
            int starts = occurrences(existing, BLOCK_START);
            int ends = occurrences(existing, BLOCK_END);
            boolean onePair = starts == 1 && ends == 1 && existing.indexOf(BLOCK_START) < existing.indexOf(BLOCK_END);
            return starts == 0 && ends == 0 || onePair ? Action.MERGE : Action.PRESERVE;
        }
        String recorded = ledger.getProperty(key);
        return recorded != null && recorded.equals(currentHash(target)) ? Action.REFRESH : Action.PRESERVE;
    }

    /**
     * Writes a file according to {@link #plan}.
     *
     * @return {@code true} when the file now holds {@code content}; {@code false} when it was preserved
     */
    public boolean write(Path target, String content) throws IOException {
        String key = key(target);
        if (!isShared(key)) {
            store(target, content);
            return true;
        }
        Action action = plan(target);
        boolean merged = MERGED.contains(key);
        boolean replaced = action == Action.REFRESH && replace.contains(key);
        if (action == Action.PRESERVE && !merged && hash(content).equals(currentHash(target))) {
            // Identical to what Camel-Kit writes: nothing to protect, so it is tracked from now on.
            action = Action.REFRESH;
        }
        if (action == Action.PRESERVE) {
            changes.put(key, new Change(key, action, saveProposal(key, merged ? block(content) : content)));
            return false;
        }
        if (action == Action.MERGE) {
            store(target, merge(Files.readString(target), content));
        } else if (merged) {
            store(target, block(content));
        } else {
            store(target, content);
            ledger.setProperty(key, hash(content));
        }
        if (replaced) {
            // Recorded only once applied, so a replacement that was skipped is still reported as having no effect.
            usedReplacements.add(key);
        }
        changes.put(key, new Change(key, action, null));
        Files.deleteIfExists(projectDir.resolve(PROPOSALS).resolve(key));
        return true;
    }

    /** Records a shared file that was left untouched without a single proposed replacement. */
    public void preserve(Path target) {
        String key = key(target);
        changes.putIfAbsent(key, new Change(key, Action.PRESERVE, null));
    }

    /** The outcome for every shared file handled so far, in the order it was handled. */
    public List<Change> changes() {
        return List.copyOf(changes.values());
    }

    /** Shared files that were left untouched because they belong to the user. */
    public List<Change> conflicts() {
        return changes.values().stream().filter(change -> change.action() == Action.PRESERVE).toList();
    }

    /** Requested replacements that were not applied, because the file did not exist or was not written. */
    public Set<String> unusedReplacements() {
        Set<String> unused = new TreeSet<>(replace);
        unused.removeAll(usedReplacements);
        return unused;
    }

    /** Persists the ledger. Entries are sorted and carry no timestamp so the file is stable under version control. */
    public void save() throws IOException {
        StringWriter raw = new StringWriter();
        ledger.store(raw, null);
        StringBuilder content = new StringBuilder(
                "# Shared files written by camel-kit init and the hash of the written content.\n"
                                                  + "# A file whose content no longer matches is treated as yours and is preserved.\n");
        raw.toString().lines().filter(line -> !line.startsWith("#")).sorted()
                .forEach(line -> content.append(line).append('\n'));
        Path ledgerFile = projectDir.resolve(LEDGER);
        Files.createDirectories(ledgerFile.getParent());
        AtomicFileWriter.write(ledgerFile, content.toString());
    }

    /** Camel-Kit's content wrapped in the markers that let a later run find and replace it. */
    static String block(String content) {
        return BLOCK_START + "\n" + BLOCK_NOTE + "\n" + content + (content.endsWith("\n") ? "" : "\n") + BLOCK_END
               + "\n";
    }

    /** Replaces the block inside {@code existing}, or appends it, keeping the file's line endings. */
    static String merge(String existing, String content) {
        boolean crlf = existing.contains("\r\n");
        String block = crlf ? block(content).replace("\r\n", "\n").replace("\n", "\r\n") : block(content);
        Matcher matcher = BLOCK.matcher(existing);
        if (matcher.find()) {
            return existing.substring(0, matcher.start()) + block + existing.substring(matcher.end());
        }
        String separator = crlf ? "\r\n" : "\n";
        String kept = existing.stripTrailing();
        return kept.isEmpty() ? block : kept + separator + separator + block;
    }

    private static int occurrences(String text, String part) {
        int count = 0;
        for (int at = text.indexOf(part); at >= 0; at = text.indexOf(part, at + part.length())) {
            count++;
        }
        return count;
    }

    private void store(Path target, String content) throws IOException {
        Path parent = target.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        AtomicFileWriter.write(target, content);
    }

    private Path saveProposal(String key, String content) throws IOException {
        Path proposal = projectDir.resolve(PROPOSALS).resolve(key);
        store(proposal, content);
        return proposal;
    }

    /** Whether initialization protects this path because a project may already own it. */
    public boolean isShared(Path target) {
        return isShared(key(target));
    }

    private static boolean isShared(String key) {
        return MERGED.contains(key) || TRACKED.contains(key);
    }

    private static String currentHash(Path target) throws IOException {
        if (!Files.isRegularFile(target, LinkOption.NOFOLLOW_LINKS)) {
            return "";
        }
        return hash(new String(Files.readAllBytes(target), StandardCharsets.UTF_8));
    }

    /** Line endings are normalized so a checkout that converts them does not look like a user edit. */
    private static String hash(String content) {
        try {
            byte[] normalized = content.replace("\r\n", "\n").getBytes(StandardCharsets.UTF_8);
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(normalized));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    private String key(Path target) {
        return key(projectDir, target.toAbsolutePath().normalize());
    }

    private static String key(Path root, Path target) {
        return target.startsWith(root) ? root.relativize(target).toString().replace('\\', '/') : target.toString();
    }
}
